import assert from 'node:assert/strict';
import { createNotesAuth } from '../assets/js/notes-auth.js';
import { requestNotes, configureNotesAuthorization } from '../assets/js/notes-api.js';

const storage = new Map();
globalThis.window = new EventTarget();
globalThis.sessionStorage = { getItem: (key) => storage.get(key) || null, setItem: (key, value) => storage.set(key, value), removeItem: (key) => storage.delete(key) };
globalThis.navigation = Object.assign(new EventTarget(), { activation: { navigationType: 'push' }, currentEntry: { key: 'entry-a' } });
const response = (payload, status = 200) => ({ ok: status < 400, status, json: async () => payload });
let calls = [];
globalThis.fetch = async (url, options) => {
    calls.push({ url, options });
    if (url.endsWith('/auth')) return response({ enabled: true, passwordRequired: true, authenticated: false, retryAfterSeconds: 0 });
    if (url.endsWith('/unlock')) return response({ token: 'test-token-a' });
    if (url.endsWith('/resume')) return response({ token: 'test-token-b' });
    return response({});
};
const auth = createNotesAuth();
assert.equal(await auth.ready(), false);
await assert.rejects(requestNotes(), (error) => error.status === 401);
assert.equal(calls.length, 1, 'Locked requests must never reach fetch');
await auth.unlock('transient-password');
assert.equal(auth.allowed, true);
assert.equal(storage.size, 0, 'Normal unlocked state keeps no persisted token');
const event = new Event('navigate'); event.navigationType = 'reload';
navigation.dispatchEvent(event);
assert.equal(storage.size, 1);
assert.ok(![...storage.values()].join().includes('transient-password'));
navigation.activation.navigationType = 'reload';
const resumed = createNotesAuth();
assert.equal(await resumed.ready(), true);
assert.equal(resumed.token, 'test-token-b');
assert.equal(storage.size, 0, 'Refresh handoff must be consumed immediately');
assert.equal(calls.at(-1).options.headers['X-Notes-Token'], 'test-token-a');
storage.set('homelab-notes-reload-v1', JSON.stringify({ token: 'copied-token', key: 'other-entry', createdAt: Date.now() }));
const mismatched = createNotesAuth();
assert.equal(await mismatched.ready(), false);
assert.equal(storage.size, 0);
navigation.activation.navigationType = 'push';
storage.set('homelab-notes-reload-v1', JSON.stringify({ token: 'copied-token', key: 'entry-a', createdAt: Date.now() }));
assert.equal(await createNotesAuth().ready(), false, 'Fresh/duplicate/restore loads cannot reuse copied storage');
assert.equal(storage.size, 0);

let finish;
const controller = { allowed: true, epoch: 1, token: 'current', invalidate() { this.allowed = false; this.epoch++; } };
configureNotesAuthorization(controller);
globalThis.fetch = async () => ({ ok: true, status: 200, json: () => new Promise((resolve) => { finish = resolve; }) });
const late = requestNotes();
await new Promise((resolve) => setImmediate(resolve));
controller.invalidate(); finish({ notes: [{ title: 'private' }] });
await assert.rejects(late, (error) => error.status === 499);
controller.allowed = true;
globalThis.fetch = async () => response({ error: 'notes_auth_required' }, 401);
await assert.rejects(requestNotes(), (error) => error.status === 401);
assert.equal(controller.allowed, false);
assert.equal(controller.epoch, 3);
globalThis.fetch = async () => response({ error: 'not_found' }, 404);
const old = createNotesAuth(); await old.ready();
assert.equal(old.allowed, false); assert.match(old.error, /升级后端/);
globalThis.fetch = async () => response({ enabled: true });
const malformed = createNotesAuth(); await malformed.ready();
assert.equal(malformed.allowed, false);
console.log('Notes authorization: locked transport, refresh handoff, copied storage, stale response, invalidation and legacy backend passed.');
